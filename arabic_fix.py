"""إصلاحات عربية مشتركة لخطي القوانين والمكتبة.

الفلسفة: لا تخمين أبداً. كل إصلاح إما تطبيع يونيكود قياسي (NFKC)،
أو خريطة صريحة من صيغ تالفة مستحيلة الصحة إلى صيغها السليمة.

التشوه المستهدف (من خرائط خطوط PDF المعطوبة وTesseract):
  "الأصل"    -> "أالصل"    (تدوير موصول اللام-ألف: [ا،ل،أ/إ] -> [أ،ا،ل])
  "الإثبات"  -> "أالثبات"
  "المعاملات" -> "المعاملت" (سقوط ألف + تاء مربوطة مقروءة تاء)

الصيغ التالفة المولدة لا تظهر في عربية سليمة أبداً، فالاستبدال
المحدد بحدود الكلمات آمن تماماً ولا يمس النص السليم.
"""

import re
import unicodedata

# كلمات قانونية سليمة شائعة تبدأ بالألف-لام-همزة: تولد صيغها التالفة آلياً.
# (الصيغة التالفة = تدوير الأحرف الثلاثة الأولى + تسطيح الهمزة)
_CORRECT_WORDS = [
    # ألف-لام-همزة فوق: الأ...
    "الأصل", "الأمر", "الأب", "الأجل", "الأثر", "الأخذ", "الأجرة", "الأجير",
    "الأحد", "الأرض", "الأسرة", "الأحوال", "الأعيان", "الأموال", "الآمر",
    "الأمين", "الأمانة", "الأهلية", "الأوصياء", "الآثار",
    # ألف-لام-همزة تحت: الإ...
    "الإثبات", "الإجراء", "الإجراءات", "الإيجار", "الإحالة", "الإخطار",
    "الإقامة", "الإرث", "الإعالة", "الإذن", "الإفراج", "الإفلاس",
    "الالتزام", "الالتزامات", "الامتناع", "الانتفاع", "الإنذار", "الاجتماع",
    "الاتفاق", "الاتفاقية", "الادعاء", "الاستئناف", "الاعتراض", "الإلغاء",
    "الإكراه", "الإخلال", "الإبراء", "الإيداع", "الإثم", "الإقليم",
    "الإدارة", "الإرادة", "الإعلان", "الإعسار", "الاقتصاد",
    # سقوط ألف + تاء مربوطة (Tesseract)
    "المعاملات", "المعاملة", "المرافعات", "المرافعة", "المثبتة",
]


def _corrupt_form(word):
    """يولد الصيغة التالفة لكلمة تبدأ [ا،ل،أ/إ]، أو None لغيرها."""
    if len(word) >= 3 and word[0] == "ا" and word[1] == "ل" and word[2] in ("أ", "إ", "آ"):
        return "أال" + word[3:]
    return None


# كلمات سليمة تبدأ [ل،ل،أ/إ/ا]: صيغتها التالفة تدوير المواضع 1-3 (للأمم -> لألمم)
_LL_CORRECT = [
    "للأمم", "للأشخاص", "للأطفال", "للأسباب", "للأدلة", "للأحكام",
    "للأفراد", "للأغراض", "للأطراف", "للأغذية", "للأحداث", "للاجئين",
    "للاعتداءات", "للاتفاق", "للاتفاقية", "للالتزامات", "للأطباء",
    "للأيتام", "للأرامل", "للأجراء", "للأمور", "للأطباء", "للآراء",
    "للآثار", "للآداب", "للأديان", "للأخبار", "للأعباء", "للأعيان",
]


def _corrupt_ll(word):
    if len(word) >= 3 and word[0] == "ل" and word[1] == "ل" and word[2] in ("أ", "إ", "ا"):
        return "ل" + word[2] + "ل" + word[3:]
    return None


def _build_word_fixes():
    fixes = {}
    for w in _CORRECT_WORDS:
        c = _corrupt_form(w)
        if c and c != w:
            fixes[c] = w
    for w in _LL_CORRECT:
        c = _corrupt_ll(w)
        if c and c != w:
            fixes[c] = w
    # شواهد مبلغ عنها صراحة (تطابق التوليد الآلي لكن نثبتها هنا توثيقاً)
    fixes.update({
        "المعاملت": "المعاملات",
        # سقوط ألف صريح مشاهَد (Tesseract) — الصيغ التالفة مستحيلة الصحة
        "التعديلت": "التعديلات",
        "الستدعاء": "الاستدعاء",
        "الولوية": "الأولوية",
    })
    # فئة اإل (إقحام همزة): مشاهدات صريحة كاملة الكلمة فقط.
    # (لا قاعدة عامة: في الركام المركب مثل اإلعبلن لا يكفي حذف الهمزة)
    fixes.update({
        "اإلجراءات": "الإجراءات",
        "واإلجراءات": "والإجراءات",
        "لإلجراءات": "للإجراءات",
        "إلجراءات": "الإجراءات",
        "باإلجراءات": "بالإجراءات",
        "ولإلجراءات": "وللإجراءات",
        "اإجراء": "الإجراء",
        "اإلحالة": "الإحالة",
        "اإليداع": "الإيداع",
        "اإلذن": "الإذن",
        "اإلخطار": "الإخطار",
        "اإلرث": "الإرث",
        "اإثبات": "الإثبات",
        "اإلقرار": "الإقرار",
        "اإدارة": "الإدارة",
        "اإلدارية": "الإدارية",
        "اإليجار": "الإيجار",
        "اإليصال": "الإيصال",
        "اإعسار": "الإعسار",
        "باإلجماع": "بالإجماع",
        "اإلشارات": "الإشارات",
        "اإللصاق": "الإلصاق",
        "اإلدعاء": "الادعاء",
        "واإللكترونية": "والإلكترونية",
        "اإلحصاءات": "الإحصاءات",
        "واإلحصاءات": "والإحصاءات",
        "واالستفتاءات": "والاستفتاءات",
    })
    return fixes


WORD_FIXES = _build_word_fixes()

# نمط حدود الكلمات للعربية (لا تعتمد \b مع الهمزات والحركات)
_WORD_PATTERN = None


def _get_word_pattern():
    global _WORD_PATTERN
    if _WORD_PATTERN is None:
        keys = sorted(WORD_FIXES.keys(), key=len, reverse=True)
        alt = "|".join(re.escape(k) for k in keys)
        _WORD_PATTERN = re.compile("(?<![\u0600-\u06FF])(" + alt + ")(?![\u0600-\u06FF])")
    return _WORD_PATTERN


def normalize_nfkc(text):
    if not text:
        return text
    try:
        text = unicodedata.normalize("NFKC", text)
    except Exception:
        pass
    # شوائب ترميز خطوط مستندات الأمم المتحدة
    text = text.replace("ѧ", "").replace("Ѧ", "")
    return text


def repair_words(text):
    """يستبدل الصيغ التالفة المعروفة بحدود الكلمات. يعيد (النص، عدد الاستبدالات)."""
    if not text:
        return text, 0
    count = [0]

    def _sub(m):
        count[0] += 1
        return WORD_FIXES[m.group(1)]

    text = _get_word_pattern().sub(_sub, text)
    return text, count[0]


def repair_text(text):
    """خط الإصلاح الكامل: تطبيع + كلمات. يعيد (النص، عدد الاستبدالات)."""
    if not text:
        return text, 0
    text = normalize_nfkc(text)
    return repair_words(text)
