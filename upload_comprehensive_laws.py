def get_auth_token():
    auth_url = f"https://identitytoolkit.googleapis.com/v1/accounts:signUp?key={API_KEY}"
    req = urllib.request.Request(
        auth_url,
        data=json.dumps({"returnSecureToken": True}).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    try:
        with urllib.request.urlopen(req) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return data.get("idToken")
    except Exception as e:
        print(f"⚠️ تعذر تسجيل الدخول المجهول: {e}")
        return None

def format_firestore_fields(data):
    fields = {
        "law_title": {"stringValue": data["law_title"]},
        "article_number": {"stringValue": data["article_number"]},
        "category": {"stringValue": data["category"]},
        "text": {"stringValue": data["text"]},
        "keywords": {
            "arrayValue": {
                "values": [{"stringValue": kw} for kw in data["keywords"]]
            }
        }
    }
    return {"fields": fields}

def upload_laws():
    print("🔑 جاري التوثيق والحصول على رمز المصادقة من Firebase...")
    token = get_auth_token()
    if token:
        print("✓ تم التوثيق بنجاح.")
    else:
        print("⚠️ المحاولة دون توكن...")

    print(f"🚀 بدء رفع حزمة القوانين ({len(laws_dataset)} مادة)...")
    success_count = 0

    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"

    for item in laws_dataset:
        doc_id = item["id"]
        url = f"{BASE_URL}/{doc_id}?updateMask.fieldPaths=law_title&updateMask.fieldPaths=article_number&updateMask.fieldPaths=category&updateMask.fieldPaths=text&updateMask.fieldPaths=keywords"
        payload = json.dumps(format_firestore_fields(item)).encode('utf-8')
        
        req = urllib.request.Request(
            url=url,
            data=payload,
            headers=headers,
            method="PATCH"
        )
        
        try:
            with urllib.request.urlopen(req) as resp:
                if resp.status in (200, 201):
                    print(f"  ✓ تم رفع [{item['law_title']}] المادة ({item['article_number']})")
                    success_count += 1
        except urllib.error.HTTPError as e:
            err_msg = e.read().decode('utf-8')
            print(f"  ❌ خطأ في رفع {doc_id}: {e.code} - {err_msg}")
        except Exception as ex:
            print(f"  ❌ استثناء: {str(ex)}")

    print(f"\n✨ اكتملت العملية: تم رفع {success_count} مادة قانونية بنجاح إلى Firestore!")

if __name__ == "__main__":
    upload_laws()
